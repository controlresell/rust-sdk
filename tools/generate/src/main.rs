//! Writes the generated client: `generate <openapi-3.0.json> <out.rs>`.
//!
//! Progenitor is used as a library, not through `cargo progenitor`: the CLI cannot ask for the hooks the hand-written
//! layer implements (retries, Idempotency-Key), and it formats with a `rustfmt` it looks for in rustup's toolchains.
//! Here the code is formatted with `prettyplease`, so the output does not depend on the machine.
use progenitor::{GenerationSettings, Generator, HooksMode, InterfaceStyle};
use quote::quote;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let [_, spec, out] = &args[..] else {
        eprintln!("usage: generate <openapi-3.0.json> <out.rs>");
        std::process::exit(2);
    };
    let spec: openapiv3::OpenAPI = serde_json::from_str(&std::fs::read_to_string(spec).expect("read the document"))
        .expect("parse the OpenAPI 3.0 document");
    let mut settings = GenerationSettings::default();
    settings
        .with_interface(InterfaceStyle::Builder)
        .with_hooks(HooksMode::Expected)
        .with_inner_type(quote!(crate::Inner));
    let mut generator = Generator::new(&settings);
    let tokens = generator.generate_tokens(&spec).expect("generate the client");
    let file = syn::parse2(tokens).expect("the generated code parses");
    let code = format!(
        "// Generated by tools/generate (Progenitor) from the OpenAPI document of the public API: do not edit.\n\
         // Regenerate with scripts/generate.sh.\n\n{}",
        prettyplease::unparse(&file)
    );
    std::fs::write(out, code).expect("write the generated code");
}
